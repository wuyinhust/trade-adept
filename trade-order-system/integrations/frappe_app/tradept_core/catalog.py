"""Company-scoped maintenance of real ERPNext Items.

No SKU, group, UOM, price or inventory is generated by this facade. Items are
not part of the five workbench snapshot collections: audit receipts preserve
before/after metadata, without promising that an old snapshot restores Items.
"""
from __future__ import annotations

import copy
import hashlib
import frappe

from .domain import APIError
from .schema import dumps, loads
from . import repository as repo
from .finance_native import object_values, text, require_usable_item

CAPABILITIES = frozenset("catalog." + action for action in ("read", "create", "write", "disable"))
FIELDS = {"item_name": "itemName", "item_group": "itemGroup", "stock_uom": "stockUom", "description": "description", "is_sales_item": "isSalesItem", "is_purchase_item": "isPurchaseItem"}
EDITABLE = frozenset(FIELDS.values())


def selectable_items(company, *, sales=None):
    result = []
    rows = frappe.get_all("Item", filters={"disabled": 0}, fields=["name", "item_name", "stock_uom", "custom_tradept_company", "is_sales_item", "is_purchase_item"], limit_page_length=1000, order_by="item_name asc")
    for row in rows:
        try:
            require_usable_item(row, company, sales=sales)
        except APIError:
            continue
        result.append({"name": row.name, "itemCode": row.name, "label": row.item_name or row.name, "uom": row.stock_uom})
    return result


class CatalogPolicy:
    def __init__(self, cfg, actor, rules, payload=None):
        self.cfg, self.actor, self.rules, self.payload = cfg, actor, rules, payload

    @property
    def scope(self):
        selected = self.rules._policy(self.cfg, self.actor).get("scope", "self")
        return selected if selected in ("self", "team", "tenant") else "self"

    def allowed(self, action):
        cap = "catalog." + action
        return self.actor.get("tenantId") == self.cfg.get("id") and cap in CAPABILITIES and self.rules.permitted(self.cfg, self.actor, cap)

    def companies(self):
        user = self.actor.get("nativeUser")
        if not user or user in ("Administrator", "Guest") or self.actor.get("tenantId") != self.cfg.get("id"):
            return {}
        grants = {row.for_value for row in frappe.get_all("User Permission", filters={"user": user, "allow": "Company"}, fields=["for_value"])}
        result = {}
        for logical in self.rules.company_ids(self.cfg, self.actor):
            native = repo.native_company(logical)
            if native and native in grants:
                result[logical] = native
        return result

    def require(self, action, company_id=None):
        if not self.allowed(action):
            raise APIError(403, "CATALOG_PERMISSION_DENIED", "当前角色没有此商品目录操作权限")
        if company_id is not None:
            company = self.companies().get(company_id)
            if not company:
                raise APIError(403, "CATALOG_COMPANY_DENIED", "当前账号没有所选公司的原生授权")
            return company
        return None

    def _owned(self, doc, action):
        if self.scope == "tenant":
            return True
        owner = doc.get("owner")
        user = self.actor.get("nativeUser")
        if owner == user or action == "create" and owner in (None, ""):
            return True
        return self.scope == "team" and bool(self.actor.get("teamId")) and any(profile.get("nativeUser") == owner and profile.get("teamId") == self.actor["teamId"] for profile in self.rules.ownership_profiles.values())

    def require_item(self, doc, action="read", company=None):
        self.require(action)
        if doc.doctype != "Item" or company not in self.companies().values():
            raise APIError(403, "CATALOG_COMPANY_DENIED", "商品目录操作必须限定已授权公司")
        tagged = doc.get("custom_tradept_company")
        if tagged and tagged != company:
            raise APIError(403, "CATALOG_ITEM_COMPANY_DENIED", "商品属于另一公司")
        if action == "create":
            if tagged != company or not self._owned(doc, action) or doc.get("is_stock_item") != 0:
                raise APIError(403, "CATALOG_CREATE_DENIED", "新建商品必须归属当前公司和操作者，并为非库存商品")
        elif action in ("write", "disable"):
            if doc.get("has_variants"):
                raise APIError(403, "CATALOG_NATIVE_TEMPLATE_REQUIRED", "变体模板会联动其他 SKU，请由原生 ERPNext 管理渠道维护")
            if tagged:
                if not self._owned(doc, action):
                    raise APIError(403, "CATALOG_SCOPE_DENIED", "商品不在当前角色可维护的本人或团队范围内")
            else:
                all_companies = {str(row["id"]) for row in self.cfg.get("companies", [])}
                if self.scope != "tenant" or not all_companies or set(self.companies()) != all_companies:
                    raise APIError(403, "CATALOG_SHARED_WRITE_DENIED", "共用商品的修改或停用需要企业范围及全部公司授权")
        return company

    validate_item = require_item

    def item_allowed(self, doc, action="read", company=None):
        try:
            self.require_item(doc, action, company)
            return True
        except APIError:
            return False


def public(doc, policy, company=None):
    tagged = doc.get("custom_tradept_company")
    company_id = next((logical for logical, native in policy.companies().items() if native == tagged), None)
    result = {"name": doc.name, "itemCode": doc.item_code, "companyId": company_id, "shared": not bool(tagged), "isStockItem": bool(doc.is_stock_item), "disabled": bool(doc.disabled), "modified": str(doc.modified), "owner": doc.owner, "modifiedBy": doc.modified_by}
    result.update({external: bool(doc.get(native)) if native in ("is_sales_item", "is_purchase_item") else doc.get(native) for native, external in FIELDS.items()})
    selected = company or tagged or next(iter(policy.companies().values()), None)
    result.update(canWrite=policy.item_allowed(doc, "write", selected), canDisable=policy.item_allowed(doc, "disable", selected))
    return result


def _company(policy, action, supplied):
    company_id = supplied.get("companyId")
    if not isinstance(company_id, str) or not company_id:
        raise APIError(400, "CATALOG_COMPANY_REQUIRED", "请选择公司主体")
    return company_id, policy.require(action, company_id)


def _load(name, policy, company, action="read", lock=False):
    name = text(name, "Item", required=True, limit=140)
    if not frappe.db.exists("Item", name):
        raise APIError(404, "CATALOG_ITEM_NOT_FOUND", "原生商品不存在")
    doc = frappe.get_doc("Item", name, for_update=True) if lock else frappe.get_doc("Item", name)
    policy.require_item(doc, action, company)
    return doc


def state(work, cfg, actor, rules, supplied):
    object_values(supplied, {"companyId", "search", "includeDisabled", "limit", "offset", "name"}, "Catalog query")
    policy = CatalogPolicy(cfg, actor, rules)
    company_id, company = _company(policy, "read", supplied)
    limit, offset = supplied.get("limit", 40), supplied.get("offset", 0)
    if type(limit) is not int or not 1 <= limit <= 100 or type(offset) is not int or not 0 <= offset <= 1000000:
        raise APIError(400, "INVALID_CATALOG_PAGINATION", "分页大小必须为 1 至 100，偏移必须为非负整数")
    if type(supplied.get("includeDisabled", False)) is not bool:
        raise APIError(400, "INVALID_CATALOG_FLAG", "includeDisabled 必须为布尔值")
    search = text(supplied.get("search"), "Search", limit=100).casefold()
    filters = {} if supplied.get("includeDisabled") else {"disabled": 0}
    # Company tags are authorization, never an Item Defaults association.
    rows = frappe.get_all("Item", filters=filters, fields=["name"], order_by="item_name asc,name asc", limit_page_length=0)
    items = []
    for row in rows:
        doc = repo.get_doc("Item", row.name)
        if policy.item_allowed(doc, "read", company) and (not search or search in str(doc.item_code).casefold() or search in str(doc.item_name).casefold()):
            items.append(public(doc, policy))
    companies = policy.companies()
    result = {"version": int(work.revision or 0), "companyId": company_id, "companies": [row for row in cfg["companies"] if row["id"] in companies], "capabilities": {cap: policy.allowed(cap.split(".")[1]) for cap in CAPABILITIES}, "items": items[offset:offset + limit], "pagination": {"offset": offset, "limit": limit, "hasMore": len(items) > offset + limit}, "options": {"itemGroups": [{"name": row.name, "label": row.name} for row in frappe.get_all("Item Group", filters={"is_group": 0}, fields=["name"], order_by="name", limit_page_length=0)], "uoms": [{"name": row.name, "label": row.name} for row in frappe.get_all("UOM", filters={"enabled": 1}, fields=["name"], order_by="name", limit_page_length=0)]}}
    if supplied.get("name"):
        result["document"] = public(_load(supplied["name"], policy, company), policy)
    return result


def _values(doc, values, *, create=False):
    object_values(values, EDITABLE | ({"itemCode"} if create else set()), "Item values")
    if create:
        doc.item_code = text(values.get("itemCode"), "Item code", required=True, limit=140)
    for native, external in FIELDS.items():
        if external not in values and not create:
            continue
        if native in ("is_sales_item", "is_purchase_item"):
            value = values.get(external, True)
            if type(value) not in (bool, int) or value not in (0, 1):
                raise APIError(400, "INVALID_CATALOG_FLAG", "销售及采购用途必须为布尔值")
            value = int(value)
        else:
            value = text(values.get(external), external, required=native != "description", limit=4000 if native == "description" else 140)
        doc.set(native, value)
    if not frappe.db.exists("Item Group", {"name": doc.item_group, "is_group": 0}):
        raise APIError(400, "CATALOG_GROUP_REQUIRED", "请选择真实的叶级商品分组")
    if not frappe.db.exists("UOM", {"name": doc.stock_uom, "enabled": 1}):
        raise APIError(400, "CATALOG_UOM_REQUIRED", "请选择已启用的真实单位")


def perform(work, cfg, actor, rules, supplied):
    object_values(supplied, {"companyId", "operation", "name", "expectedVersion", "expectedModified", "idempotencyKey", "values"}, "Catalog operation")
    op = supplied.get("operation")
    if op not in ("create", "save", "disable"):
        raise APIError(404, "CATALOG_OPERATION_NOT_FOUND", "未知商品维护动作")
    action = "write" if op == "save" else op
    policy = CatalogPolicy(cfg, actor, rules)
    company_id, company = _company(policy, action, supplied)
    key = text(supplied.get("idempotencyKey"), "Operation key", required=True, limit=200)
    kind = "catalog:" + hashlib.sha256(dumps([cfg["id"], actor["nativeUser"], company_id, op, key]).encode()).hexdigest()
    intent = {key: value for key, value in supplied.items() if key not in ("expectedVersion", "expectedModified")}
    request_hash = hashlib.sha256(dumps(intent).encode()).hexdigest()
    rows = frappe.get_all("Trade Audit", filters={"kind": kind, "actor_id": actor["id"]}, fields=["summary"], order_by="revision desc", limit_page_length=1)
    if rows:
        receipt = loads(rows[0].summary, {})
        if receipt.get("requestSha256") != request_hash:
            raise APIError(409, "IDEMPOTENCY_CONFLICT", "该操作键已用于不同商品维护内容")
        doc = _load(receipt["itemName"], policy, company, action)
        return {**receipt["result"], "document": public(doc, policy), "replayed": True}
    expected = supplied.get("expectedVersion")
    if type(expected) is not int or expected < 0:
        raise APIError(400, "EXPECTED_VERSION_REQUIRED", "商品维护需要当前工作区版本")
    if expected != int(work.revision or 0):
        raise APIError(409, "VERSION_CONFLICT", "数据已变化，请重新加载商品目录", latestVersion=int(work.revision or 0))
    values = supplied.get("values", {})
    if not isinstance(values, dict):
        raise APIError(400, "INVALID_CATALOG_VALUES", "商品内容必须为对象")
    before = None
    if op == "create":
        doc = frappe.new_doc("Item")
        doc.custom_tradept_company, doc.owner, doc.is_stock_item = company, actor["nativeUser"], 0
        _values(doc, values, create=True)
        if frappe.db.exists("Item", doc.item_code):
            raise APIError(409, "CATALOG_ITEM_EXISTS", "该商品编码已存在，不能重复建立 SKU")
    else:
        doc = _load(supplied.get("name"), policy, company, action, lock=True)
        modified = supplied.get("expectedModified")
        if not isinstance(modified, str) or not modified:
            raise APIError(400, "EXPECTED_MODIFIED_REQUIRED", "需要原生商品当前修改时间")
        if modified != str(doc.modified):
            raise APIError(409, "STALE_DOCUMENT", "商品已被他人修改，请重新加载", latestModified=str(doc.modified))
        before = public(doc, policy)
        if op == "disable":
            object_values(values, {"disabled"}, "Item status")
            disabled = values.get("disabled", True)
            if type(disabled) is not bool:
                raise APIError(400, "INVALID_CATALOG_FLAG", "disabled 必须为布尔值")
            doc.disabled = int(disabled)
        else:
            _values(doc, values)
    policy.require_item(doc, action, company)
    from .permissions import delegated_catalog_operation
    from .events import managed_write
    with managed_write(), delegated_catalog_operation(action, policy, document=doc, company=company):
        if op == "create":
            explicit_code = doc.item_code
            doc.insert(ignore_permissions=True)
            if doc.item_code != explicit_code or doc.name != explicit_code:
                raise APIError(409, "CATALOG_EXPLICIT_CODE_REQUIRED", "ERPNext 商品命名配置改变了显式编码，请管理员配置按商品编码命名")
        else:
            doc.save(ignore_permissions=True)
    saved = repo.get_doc("Item", doc.name)
    result = {"document": public(saved, policy), "version": int(work.revision or 0) + 1, "snapshotRestoresItem": False}
    audit = {"requestSha256": request_hash, "itemName": saved.name, "operation": op, "companyId": company_id, "before": before, "after": result["document"], "snapshotRestoresItem": False, "result": copy.deepcopy(result)}
    receipt = repo.finish(work, actor, kind, audit)
    result.update(ok=True, meta=receipt["meta"])
    return result
